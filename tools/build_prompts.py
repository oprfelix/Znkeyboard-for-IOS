#!/usr/bin/env python3
"""Writes Prompts.generated.swift from the Android keyboard's prompts, so both apps ask the same.

Usage: tools/build_prompts.py <assets/prompts> <Prompts.generated.swift>
"""
import pathlib
import sys

source, out = pathlib.Path(sys.argv[1]), sys.argv[2]
names = {"rewrite": "rewrite_base.md", "translate": "translate.md", "read": "read.md"}
lines = ["// Generated by tools/build_prompts.py; do not edit by hand.", "", "enum Prompts {"]
for name, file in names.items():
    body = (source / file).read_text(encoding="utf8").strip().replace("\\", "\\\\").replace('"""', '\\"""')
    lines += [f'    static let {name} = """', *["    " + l if l else "" for l in body.split("\n")], '    """', ""]
lines[-1] = "}"
open(out, "w", encoding="utf8").write("\n".join(lines) + "\n")
